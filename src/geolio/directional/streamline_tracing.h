#ifndef GEOLIO_STREAMLINE_TRACING_H
#define GEOLIO_STREAMLINE_TRACING_H
#include <geogram/mesh/mesh.h>
#include <geogram/mesh/mesh_AABB.h>
#include <cassert>

#include "geolio/common/utils.h"

namespace geolio
{
    /**
     * @brief Base class for streamline tracing on a mesh.
     *
     * This class maintains the seed points, local direction data, and the traced
     * streamline path for a given mesh. Derived classes specialize the element
     * geometry and local tracing rules for surface or volumetric meshes.
     */
    class StreamlineTracer {
    public:
        /**
         * @brief Constructs a streamline tracer bound to a mesh.
         * @param[in] mesh Reference to the mesh on which streamline tracing is performed.
         */
        explicit StreamlineTracer(GEO::Mesh& mesh) : attribute_id_(generate_random_string(22)), mesh_(mesh) {}

        /**
         * @brief Destroys the tracer and releases associated mesh attributes.
         */
        virtual ~StreamlineTracer() {
            if (mesh_element_direction_.is_bound())
                mesh_element_direction_.destroy();
        }

        /**
         * @brief Sets the initial seed points for tracing.
         * @param[in] points_nb Number of seed points.
         * @param[in] points Pointer to a flat array of seed coordinates in XYZ order.
         * The buffer is expected to contain `3 * points_nb` doubles.
         */
        virtual void set_initial_points(GEO::index_t points_nb, const double* points);

        /**
         * @brief Traces streamlines for the specified number of iterations.
         * @param[in] iterations Number of tracing steps to execute for each seed point.
         */
        void trace(GEO::index_t iterations);

        /**
         * @brief Appends traced points to an output mesh as vertex data.
         * @param[in] mesh Target mesh receiving the traced vertices and associated attributes.
         * @param[in,out] mesh_v_tracing_times Optional vertex attribute storing the number of tracing
         * steps recorded for each vertex. If not null, it is filled during the append operation.
         * @param[in,out] mesh_e_point_idx Optional attribute used to store the mapped point index on
         * mesh elements. If not null, it is filled during the append operation.
         */
        void append_tracing_points_to_mesh(
            GEO::Mesh& mesh,
            GEO::Attribute<GEO::index_t>* mesh_v_tracing_times = nullptr,
            GEO::Attribute<GEO::index_t>* mesh_e_point_idx = nullptr) const;

        /**
         * @brief Returns the traced streamline points.
         * @return Const reference to the internal point sequence generated by tracing.
         */
        const auto& traced_points() { return traced_points_; }

    protected:
        /**
         * @brief Initializes the per-point-to-element association used during tracing.
         */
        virtual void initialize_points_locate_element() = 0;

        /**
         * @brief Computes the direction vector at a given mesh vertex.
         * @param[in] v Index of the mesh vertex to query.
         * @return Direction vector associated with the vertex.
         */
        GEO::vec3 get_point_direction(GEO::index_t v);

        /**
         * @brief Advances tracing from a current vertex to the next point and element.
         * @param[in] v Index of the current mesh vertex.
         * @param[out] next_point Coordinates of the next traced point.
         * @param[out] next_element Index of the next mesh element containing the tracing result.
         * @param[out] next_local_idx Local index of the next point within the target element.
         */
        virtual void trace_point(GEO::index_t v, GEO::vec3& next_point, GEO::index_t& next_element, GEO::index_t& next_local_idx) = 0;

        const std::string attribute_id_;

        GEO::Mesh& mesh_;

        GEO::index_t points_nb_ = 0;
        GEO::index_t traced_times_ = 0;

        struct TracingPoint {
            GEO::vec3 point;
            GEO::index_t element = GEO::NO_INDEX; // f / c
            GEO::index_t local_idx = GEO::NO_INDEX; // lv / lf
        };
        std::vector<TracingPoint> traced_points_; // points_nb * tracing_times

        GEO::index_t N_ = 0;
        GEO::Attribute<double> mesh_element_direction_;
    };

    /* ============================================================================================================= */

    /**
     * @brief Traces streamlines constrained to a triangular surface mesh.
     */
    class StreamlineSurficialTracer : public StreamlineTracer {
    public:
        /**
         * @brief Constructs a surface tracer for a triangle mesh.
         * @param[in] mesh Reference to a simplicial surface mesh.
         */
        explicit StreamlineSurficialTracer(GEO::Mesh& mesh) : StreamlineTracer(mesh) {
            assert(mesh_.vertices.dimension() > 2);
            assert(mesh_.facets.nb() > 0);
            assert(mesh_.facets.are_simplices());
            mesh_AABB_.initialize(mesh_);

            mesh_f_unit_normal_.bind(mesh_.facets.attributes(), attribute_id_+":unit_normal");
            for (const auto& f : mesh_.facets)
                mesh_f_unit_normal_[f] = GEO::normalize(GEO::Geom::triangle_normal(
                    mesh_.facets.point(f, 0),
                    mesh_.facets.point(f, 1),
                    mesh_.facets.point(f, 2)));
        }

        /**
         * @brief Destroys the surface tracer and releases its per-facet normal attribute.
         */
        ~StreamlineSurficialTracer() override {
            if (mesh_f_unit_normal_.is_bound())
                mesh_f_unit_normal_.destroy();
        }

        /**
         * @brief Sets a per-vertex direction field for the surface mesh.
         * @param[in] N Number of direction vectors.
         * @param[in] directions Pointer to a flat array of direction components stored as `(dx, dy, dz)`
         * triplets for each vertex.
         */
        void set_per_vertex_directions(GEO::index_t N, const double* directions);

        /**
         * @brief Sets a per-facet direction field for the surface mesh.
         * @param[in] N Number of direction vectors.
         * @param[in] directions Pointer to a flat array of direction components stored as `(dx, dy, dz)`
         * triplets for each facet.
         */
        void set_per_facet_directions(GEO::index_t N, const double* directions);

        /**
         * @brief Smooths the direction field while keeping the streamline on the surface.
         * @param[in] iterations Number of smoothing iterations. Default is 3.
         * @param[in] damping Relaxation factor controlling the smoothing strength. Default is 0.5.
         * @param[in] constraint_on_surface If true, the smoothed directions are constrained to the local
         * surface tangent plane.
         */
        void smooth(GEO::index_t iterations = 3, double damping = 0.5, bool constraint_on_surface = true);

    protected:
        /**
         * @brief Initializes the element lookup used to locate tracing points on the surface.
         */
        void initialize_points_locate_element() override;

        /**
         * @brief Computes the next traced point and its target element during surface tracing.
         * @param[in] v Index of the current mesh vertex.
         * @param[out] next_point Coordinates of the next traced point.
         * @param[out] next_element Index of the next mesh facet containing the continuation point.
         * @param[out] next_local_idx Local index of the point within the target facet.
         */
        void trace_point(GEO::index_t v, GEO::vec3& next_point, GEO::index_t& next_element, GEO::index_t& next_local_idx) override;

        GEO::MeshFacetsAABB mesh_AABB_;
        GEO::Attribute<GEO::vec3> mesh_f_unit_normal_;
    };

    /* ============================================================================================================= */

    /**
     * @brief Traces streamlines through a volumetric tetrahedral mesh.
     */
    class StreamlineVolumetricTracer : public StreamlineTracer {
    public:
        /**
         * @brief Constructs a volumetric tracer for a simplicial 3D mesh.
         * @param[in] mesh Reference to a tetrahedral or simplex cell mesh.
         */
        explicit StreamlineVolumetricTracer(GEO::Mesh& mesh) : StreamlineTracer(mesh) {
            assert(mesh_.cells.nb() > 0);
            assert(mesh_.cells.are_simplices());
            mesh_AABB_.initialize(mesh_);
        }

        /**
         * @brief Sets a per-vertex direction field for the volumetric mesh.
         * @param[in] N Number of direction vectors.
         * @param[in] directions Pointer to a flat array of direction components stored as `(dx, dy, dz)`
         * triplets for each vertex.
         */
        void set_per_vertex_directions(GEO::index_t N, const double* directions);

        /**
         * @brief Sets a per-cell direction field for the volumetric mesh.
         * @param[in] N Number of direction vectors.
         * @param[in] directions Pointer to a flat array of direction components stored as `(dx, dy, dz)`
         * triplets for each cell.
         */
        void set_per_cell_directions(GEO::index_t N, const double* directions);

        /**
         * @brief Smooths the direction field used by volumetric streamline tracing.
         * @param[in] iterations Number of smoothing iterations. Default is 3.
         * @param[in] damping Relaxation factor controlling the smoothing strength. Default is 0.5.
         */
        void smooth(GEO::index_t iterations = 3, double damping = 0.5);

    protected:
        /**
         * @brief Initializes the element lookup used to locate tracing points inside the volume.
         */
        void initialize_points_locate_element() override;

        /**
         * @brief Computes the next traced point and the target volume element.
         * @param[in] v Index of the current mesh vertex.
         * @param[out] next_point Coordinates of the next traced point.
         * @param[out] next_element Index of the next mesh cell containing the continuation point.
         * @param[out] next_local_idx Local index of the point within the target cell.
         */
        void trace_point(GEO::index_t v, GEO::vec3& next_point, GEO::index_t& next_element, GEO::index_t& next_local_idx) override;

        GEO::MeshCellsAABB mesh_AABB_;
    };
}

#endif //GEOLIO_STREAMLINE_TRACING_H
